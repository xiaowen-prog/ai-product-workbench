def create_development_task(project: Project, product: str, prd_dir: Path, kit_root: Path) -> BackendBuild:
    """Create the original kit Task and attach the confirmed PRD as an Artifact."""

    if project.backend and project.backend.teacher_task_id:
        return project.backend

    brief = (
        f"产品项目：{project.id}\n"
        f"开发目录：{product}\n"
        f"PRD 目录：{prd_dir}\n"
        "请按 idea-to-launch-kit 的原始阶段顺序执行，并保留每个阶段的任务、事件和产物。"
    )
    # Read the kit-generated task before creating the teacher Task. This keeps
    # a missing or stale kit gate from leaving an orphaned Task in the local DB.
    kit_stage, kit_status = read_kit_state(kit_root=kit_root, product=product)
    task_path, task_text = read_kit_task(kit_root, product)
    with SessionLocal() as session:
        task = create_task(session, TaskCreate(title=project.workshop.name or product, brief=brief))
        prd_path = prd_dir / "PRD.md"
        artifact = Artifact(
            id=str(uuid4()),
            task_id=task.id,
            name="PRD.md",
            kind="prd",
            path=str(prd_path),
            status="ready",
        )
        session.add(artifact)
        _event(session, task, "artifact_attached", "已把确认后的 PRD 作为开发输入产物挂接到任务", {"artifact": "PRD.md", "path": str(prd_path)})
        session.commit()
        return BackendBuild(
            status="stage_task_ready",
            launch_project=product,
            teacher_task_id=task.id,
            execution_mode="original_kit",
            kit_stage=kit_stage,
            kit_status=kit_status,
            kit_task_path=str(task_path),
            kit_task=task_text,
            checks=[
                "PRD、方案、结构化方案和迭代记录已写入开发项目的 docs/PRD",
                "确认后的 PRD 已挂接到老师 Task 的 Artifact",
                "Idea to Launch 已生成当前阶段任务文件",
            ],
            acceptance=[
                "阶段 0 PRD 体检及人工验收",
                "阶段 1 技术适配及人工验收",
                "阶段 2 后端 MVP、Swagger 和测试验收",
            ],
        )


def launch_kit_root() -> Path:
    raw = os.getenv("IDEA_TO_LAUNCH_KIT_ROOT", "").strip()
    if not raw:
        raise ValueError("未配置本地 Idea to Launch 工具包")
    root = Path(raw).resolve()
    if not (root / "kit.sh").is_file() or not (root / "verify.sh").is_file():
        raise ValueError("开发工具包缺少 kit.sh 或 verify.sh")
    return root



def _read_state(kit_root: Path, product: str) -> dict[str, str]:
    state_path = kit_root / "projects" / product / "docs" / "流程状态.txt"
    if not state_path.is_file():
        return {}
    values: dict[str, str] = {}
    for line in state_path.read_text(encoding="utf-8", errors="replace").splitlines():
        if "=" in line:
            key, value = line.split("=", 1)
            values[key.strip()] = value.strip()
    return values


def read_kit_state(kit_root: Path, product: str) -> tuple[str | None, str | None]:
    state = _read_state(kit_root, product)
    return state.get("阶段"), state.get("状态")


def read_kit_task(kit_root: Path, product: str) -> tuple[Path, str]:
    """Read the exact stage task generated by the original kit gate."""
    path = kit_root / "projects" / product / "docs" / "本阶段任务.md"
    if not path.is_file():
        raise ValueError("老师工具包没有生成本阶段任务文件，请先运行 kit.sh 任务")
    content = path.read_text(encoding="utf-8", errors="replace").strip()
    if not content:
        raise ValueError("老师工具包的本阶段任务文件为空")
    return path, content


def verify_kit(backend: BackendBuild, kit_root: Path) -> dict[str, Any]:
    if not backend.launch_project:
        raise ValueError("开发项目尚未创建")
    task_path, task_text = read_kit_task(kit_root, backend.launch_project)
    result = subprocess.run(
        ["bash", str(kit_root / "kit.sh"), "自检", backend.launch_project],
        cwd=kit_root,
        capture_output=True,
        text=True,
        timeout=120,
        check=False,
    )
    output = (result.stdout + result.stderr).strip()[-20_000:]
    stage, status = read_kit_state(kit_root, backend.launch_project)
    backend.kit_stage = stage
    backend.kit_status = "passed" if result.returncode == 0 else "failed"
    backend.kit_task_path = str(task_path)
    backend.kit_task = task_text
    backend.kit_last_output = output
    return {
        "ok": result.returncode == 0,
        "returncode": result.returncode,
        "stage": stage,
        "status": status,
        "task_path": str(task_path),
        "task": task_text,
        "output": output,
    }


def advance_kit(backend: BackendBuild, kit_root: Path, next_stage: str | None = None) -> dict[str, Any]:
    if not backend.launch_project:
        raise ValueError("开发项目尚未创建")
    if backend.kit_status != "passed":
        raise ValueError("必须先通过老师工具包自检，才能进入产品经理验收")
    command = ["bash", str(kit_root / "kit.sh"), "通过", backend.launch_project]
    if next_stage:
        command.append(next_stage)
    result = subprocess.run(command, cwd=kit_root, capture_output=True, text=True, timeout=30, check=False)
    ok = result.returncode == 0
    output_parts = [(result.stdout + result.stderr).strip()]
    stage, status = read_kit_state(kit_root, backend.launch_project)
    backend.kit_stage = stage
    if result.returncode != 0:
        backend.kit_status = "failed"
    elif stage == "完成":
        # ``kit.sh 通过`` is the authoritative stage transition.  Keep the
        # terminal state explicit so callers do not need a second read.
        backend.kit_status = "completed"
    else:
        backend.kit_status = "awaiting_work"
    if result.returncode == 0 and stage and stage != "完成":
        # ``kit.sh 通过`` only advances the state. Generate the next exact
        # task before returning so the next coding run cannot reuse stale
        # instructions from the previous stage.
        task_result = subprocess.run(
            ["bash", str(kit_root / "kit.sh"), "任务", backend.launch_project],
            cwd=kit_root,
            capture_output=True,
            text=True,
            timeout=30,
            check=False,
        )
        output_parts.append((task_result.stdout + task_result.stderr).strip())
        if task_result.returncode != 0:
            ok = False
            backend.kit_status = "failed"
        else:
            stage, status = read_kit_state(kit_root, backend.launch_project)
            backend.kit_stage = stage
            try:
                task_path, task_text = read_kit_task(kit_root, backend.launch_project)
            except ValueError:
                task_path, task_text = None, ""
            if task_path:
                backend.kit_task_path = str(task_path)
                backend.kit_task = task_text
            else:
                ok = False
                backend.kit_status = "failed"
    backend.kit_last_output = "\n".join(part for part in output_parts if part)[-20_000:]
    output = backend.kit_last_output
    return {
        "ok": ok,
        "returncode": result.returncode,
        "stage": stage,
        "status": status,
        "task_path": backend.kit_task_path,
        "task": backend.kit_task,
        "output": output,
    }


def development_snapshot(backend: BackendBuild) -> dict[str, object]:
    """Read the original Task and artifact state without creating a coding run.

    The idea-to-launch-kit stage is executed by its external coding tool. Any
    AgentRun that already exists on the teacher Task is a legacy runtime record
    and must not be reported as this stage's executor.
    """

    if not backend.teacher_task_id:
        return {"status": "not_started", "task": None, "run": None}
    with SessionLocal() as session:
        task = get_task(session, backend.teacher_task_id)
        return {
            "status": task.status,
            "task": {
                "id": task.id,
                "title": task.title,
                "status": task.status,
                "events": len(task.events),
                "artifacts": [
                    {"id": item.id, "name": item.name, "kind": item.kind, "path": item.path, "status": item.status}
                    for item in task.artifacts
                ],
            },
            "run": None,
        }


def run_development(backend: BackendBuild, execution_mode: str = "real") -> tuple[BackendBuild, dict[str, object]]:
    """Prepare the original kit stage for its external coding-tool handoff.

    The original ``kit.sh`` route opens a separate coding tool after writing
    ``docs/本阶段任务.md``. It does not run the teacher backend's generic
    AgentRun as a substitute for that coding tool. This adapter therefore
    only loads the exact stage task and returns the command/prompt needed by
    the external tool. ``kit.sh 自检`` remains the completion signal.
    """

    if execution_mode != "real":
        raise ValueError("真实开发链路不支持 mock 执行模式")
    if not backend.teacher_task_id:
        raise ValueError("开发任务尚未创建")
    if not backend.launch_project:
        raise ValueError("开发项目尚未创建")
    kit_root = launch_kit_root()
    task_path, task_text = read_kit_task(kit_root, backend.launch_project)
    stage, kit_state = read_kit_state(kit_root, backend.launch_project)
    backend.kit_task_path = str(task_path)
    backend.kit_task = task_text
    backend.kit_stage = stage
    backend.kit_status = kit_state or "做中"
    backend.execution_mode = "original_kit"
    backend.status = "awaiting_external_coding"
    backend.teacher_run_id = None
    backend.checks = list(dict.fromkeys([
        *backend.checks,
        "已加载老师 kit.sh 生成的本阶段任务",
        "等待外部编码工具按本阶段任务修改产品文件",
    ]))
    task_command = f"cd {kit_root} && bash kit.sh"
    snapshot = development_snapshot(backend)
    snapshot.update({
        "status": backend.status,
        "run_id": None,
        "run_status": "external_tool_required",
        "execution_mode": backend.execution_mode,
        "stage": backend.kit_stage,
        "kit_status": backend.kit_status,
        "stage_task_path": backend.kit_task_path,
        "stage_task": backend.kit_task,
        "external_command": task_command,
        "external_prompt": f"请读取 {task_path}，按其中要求完成阶段 {stage or '当前阶段'}。",
    })
    return backend, snapshot

